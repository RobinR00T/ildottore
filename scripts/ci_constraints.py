"""Print the constraints file the PR jobs of ``ci.yml`` install with (OD-49, u14 A-123).

Every job used to install the newest release of every dependency, so a release broke the next PR
whatever it changed (the train broke twice on typer 0.27.3 the day it came out). The PR jobs now
install ``pip install -c ci-constraints-requirements.txt -e ".[dev]"``: every package of the set,
direct and transitive, at one version. Dependabot's pip ecosystem bumps the pins weekly (the
name ends in ``requirements.txt`` so it reads the file), and the ``newest`` job of ``audit.yml``
installs with no constraints every night, so a break in a new release is reported the day it
lands, outside any PR.

The set is what pip's resolver picks today for the CI interpreter (CPython 3.11 on Linux
x86_64), wheels only, from the runtime dependencies, the ``dev`` extra and ``hatchling`` (the
``package`` job's build backend). It needs PyPI: run it again after a change to
``pyproject.toml``, or when a Dependabot bump of one pin conflicts with another.

usage: python scripts/ci_constraints.py > ci-constraints-requirements.txt
"""

from __future__ import annotations

import json
import re
import subprocess
import sys
import tempfile
import tomllib
from pathlib import Path

#: The interpreter and platform the PR jobs run on (``actions/setup-python`` 3.11, ubuntu-latest).
PYTHON_VERSION = "3.11"
PLATFORMS = ("manylinux_2_28_x86_64", "manylinux_2_17_x86_64", "manylinux2014_x86_64")
ABIS = ("cp311", "abi3", "none")
#: Installed by the ``package`` job beside the dev extra.
EXTRA = ("hatchling",)

HEADER = (
    "# The dependency set the PR jobs of .github/workflows/ci.yml install (OD-49, u14 A-123):\n"
    "# CPython 3.11 on Linux x86_64. Generated by scripts/ci_constraints.py; bumped by\n"
    "# Dependabot. audit.yml's newest job installs without it every night.\n"
)


def requirements(pyproject: str) -> list[str]:
    """The requirements to resolve: ``pyproject``'s runtime and ``dev`` ones, and :data:`EXTRA`."""

    project = tomllib.loads(pyproject)["project"]
    return [*project["dependencies"], *project["optional-dependencies"]["dev"], *EXTRA]


def _canonical(name: str) -> str:
    """A distribution name in its PEP 503 form, as Dependabot and pip compare them."""

    return re.sub(r"[-_.]+", "-", name).lower()


def constraints(report: dict[str, object]) -> list[str]:
    """``name==version`` per package pip's install report would install, sorted by name."""

    installs = report.get("install")
    if not isinstance(installs, list) or not installs:
        raise ValueError("pip's report installs nothing")
    pins = {_canonical(item["metadata"]["name"]): item["metadata"]["version"] for item in installs}
    return [f"{name}=={version}" for name, version in sorted(pins.items())]


def resolve(reqs: list[str]) -> dict[str, object]:
    """Run pip's resolver for the CI interpreter, installing nothing, and return its report."""

    with tempfile.TemporaryDirectory() as tmp:
        report = Path(tmp) / "report.json"
        command = [
            sys.executable, "-m", "pip", "install", "--dry-run", "--ignore-installed", "--quiet",
            "--report", str(report), "--python-version", PYTHON_VERSION,
            "--implementation", "cp", "--only-binary=:all:",
            *(f"--platform={p}" for p in PLATFORMS), *(f"--abi={a}" for a in ABIS), *reqs,
        ]  # fmt: skip
        subprocess.run(command, check=True)  # noqa: S603 - this interpreter, fixed arguments
        loaded: dict[str, object] = json.loads(report.read_text(encoding="utf-8"))
        return loaded


def main(argv: list[str]) -> int:
    pyproject = Path(argv[1] if len(argv) > 1 else "pyproject.toml").read_text(encoding="utf-8")
    sys.stdout.write(
        HEADER + "".join(f"{line}\n" for line in constraints(resolve(requirements(pyproject))))
    )
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv))
